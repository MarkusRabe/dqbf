"""Random BV-level EQFOB generator.

Builds random EQFOB problems (∃ functions over bit-vectors) and compiles
them to DQDIMACS. The `.eqfob` source is written alongside the compiled
`.dqdimacs.gz` so the high-level meaning of every instance is in-tree;
the DQDIMACS gets a provenance comment header naming the source file,
seed, and generator.

Mode controls constraint count: `under` (1–2, likely SAT), `over` (5–7,
likely UNSAT), `mixed` (3–4).
"""

from __future__ import annotations

import gzip
import json
import random
from dataclasses import dataclass
from pathlib import Path

import click

from core import dqdimacs
from core.formula import Formula
from tools.eqfob.eqfob.bitblast import bitblast
from tools.eqfob.eqfob.parse import parse
from tools.eqfob.eqfob.typecheck import check

# Avoid `-` (binary and unary): the EQFOB grammar's MINUS/ADDOP terminal
# overlap means `a - b` does not currently parse. Avoid `*` to keep
# bit-blasted instances small.
BV_BIN = ["+", "&", "|", "^"]
BV_UN = ["~"]
CMP = ["==", "!=", "<", "<=", ">", ">="]
BOOL_BIN = ["&&", "||"]

MODE_CONSTRAINTS = {"under": (1, 2), "over": (5, 7), "mixed": (3, 4)}


@dataclass(frozen=True)
class Spec:
    width: int
    n_funs: int
    n_forall: int
    n_constraints: int
    seed: int
    mode: str


def _leaf(rnd: random.Random, funs: list[str], xs: list[str]) -> str:
    """A typed (width-inferable) leaf: a forall var or a fun application."""
    if funs and rnd.random() < 0.5:
        return f"{rnd.choice(funs)}({rnd.choice(xs)})"
    return rnd.choice(xs)


def _bv_expr(rnd: random.Random, funs: list[str], xs: list[str], width: int, depth: int) -> str:
    """Always returns a width-inferable expression (never a bare constant)."""
    if depth == 0:
        return _leaf(rnd, funs, xs)
    r = rnd.random()
    if r < 0.6:
        a = _bv_expr(rnd, funs, xs, width, depth - 1)
        # Constants only ever appear as the *second* operand of a binop,
        # so width inference always has a typed side to unify against.
        if rnd.random() < 0.25:
            b: str = str(rnd.randrange(0, 1 << width))
        else:
            b = _bv_expr(rnd, funs, xs, width, depth - 1)
        return f"({a} {rnd.choice(BV_BIN)} {b})"
    if r < 0.75:
        return f"~{_leaf(rnd, funs, xs)}"
    return _leaf(rnd, funs, xs)


def _constraint(rnd: random.Random, funs: list[str], xs: list[str], width: int) -> str:
    def cmp_atom() -> str:
        a = _bv_expr(rnd, funs, xs, width, depth=2)
        b = _bv_expr(rnd, funs, xs, width, depth=2)
        return f"({a} {rnd.choice(CMP)} {b})"

    if rnd.random() < 0.4:
        return cmp_atom()
    return f"({cmp_atom()} {rnd.choice(BOOL_BIN)} {cmp_atom()})"


def gen_eqfob(spec: Spec) -> str:
    rnd = random.Random(spec.seed)
    funs = [f"f{i}" for i in range(spec.n_funs)]
    xs = [f"x{i}" for i in range(spec.n_forall)]
    lines: list[str] = [
        f"-- random_bv seed={spec.seed} mode={spec.mode} width={spec.width}",
        f"param N = {spec.width}",
        "",
    ]
    for f in funs:
        lines.append(f"fun {f} : bv[N] -> bv[N]")
    lines.append("")
    for x in xs:
        lines.append(f"forall {x} : bv[N]")
    lines.append("")
    for _ in range(spec.n_constraints):
        lines.append(_constraint(rnd, funs, xs, spec.width))
    return "\n".join(lines) + "\n"


def compile_eqfob(src: str, width: int) -> Formula:
    return bitblast(check(parse(src), overrides={"N": width}))


def write_instance(spec: Spec, outdir: Path, name: str) -> dict:
    outdir.mkdir(parents=True, exist_ok=True)
    src = gen_eqfob(spec)
    eqfob_path = outdir / f"{name}.eqfob"
    eqfob_path.write_text(src)
    f = compile_eqfob(src, spec.width)
    dq_path = outdir / f"{name}.dqdimacs.gz"
    header = (
        f"c generated by benchmarks/train/random_bv/generate.py\n"
        f"c source: {eqfob_path.name}\n"
        f"c seed={spec.seed} mode={spec.mode} width={spec.width} "
        f"n_funs={spec.n_funs} n_forall={spec.n_forall} n_constraints={spec.n_constraints}\n"
    )
    with gzip.open(dq_path, "wt") as fp:
        fp.write(header + dqdimacs.dumps(f))
    return {
        "path": dq_path.name,
        "expected": "unknown",
        "tags": ["random_bv", spec.mode],
        "params": {
            "seed": spec.seed,
            "mode": spec.mode,
            "width": spec.width,
            "n_funs": spec.n_funs,
            "n_forall": spec.n_forall,
            "n_constraints": spec.n_constraints,
        },
        "source": eqfob_path.name,
    }


def build_family(mode: str, base: Path, n_inst: int, width: int, seed0: int) -> int:
    outdir = base / mode
    lo, hi = MODE_CONSTRAINTS[mode]
    rnd = random.Random(seed0)
    manifest = []
    for i in range(n_inst):
        seed = seed0 + i
        spec = Spec(
            width=width,
            n_funs=rnd.choice([1, 2]),
            n_forall=rnd.choice([1, 2]),
            n_constraints=rnd.randint(lo, hi),
            seed=seed,
            mode=mode,
        )
        manifest.append(write_instance(spec, outdir, f"{mode}_s{seed:04d}"))
    (outdir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"wrote {len(manifest)} instances to {outdir}/")
    return len(manifest)


@click.command()
@click.option("--out", type=click.Path(), default="benchmarks/train/random_bv")
@click.option("--width", "-N", type=int, default=2)
@click.option("--n-funs", type=int, default=2, help="(single-instance mode only)")
@click.option("--n-forall", type=int, default=2, help="(single-instance mode only)")
@click.option("--n-constraints", type=int, default=3, help="(single-instance mode only)")
@click.option("--seed", type=int, default=0)
@click.option("--mode", type=click.Choice(["under", "over", "mixed", "all"]), default="all")
@click.option("--n-instances", type=int, default=15)
def main(
    out: str,
    width: int,
    n_funs: int,
    n_forall: int,
    n_constraints: int,
    seed: int,
    mode: str,
    n_instances: int,
) -> None:
    base = Path(out)
    if mode == "all":
        total = 0
        for i, m in enumerate(("under", "mixed", "over")):
            total += build_family(m, base, n_instances, width, seed0=seed + i * 1000)
        print(f"total: {total}")
        return
    spec = Spec(
        width=width,
        n_funs=n_funs,
        n_forall=n_forall,
        n_constraints=n_constraints,
        seed=seed,
        mode=mode,
    )
    print(gen_eqfob(spec))


if __name__ == "__main__":
    main()
